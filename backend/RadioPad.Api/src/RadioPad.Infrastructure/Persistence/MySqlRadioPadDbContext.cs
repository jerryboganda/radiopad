using Microsoft.EntityFrameworkCore;

namespace RadioPad.Infrastructure.Persistence;

/// <summary>
/// The MySQL/MariaDB flavour of <see cref="RadioPadDbContext"/>. It adds nothing to the model; it exists so the
/// MySQL migrations are a separate set: EF only loads migrations tagged <c>[DbContext(typeof(MySqlRadioPadDbContext))]</c>
/// for this type, so the hand-written SQLite migrations (TEXT/INTEGER columns) are never applied to MySQL.
/// Registered as the <see cref="RadioPadDbContext"/> service when <c>RADIOPAD_DB_PROVIDER</c> is mysql/mariadb,
/// so every consumer keeps resolving <see cref="RadioPadDbContext"/>.
/// Generated by the 'mysql-migrations' workflow into <c>Migrations/MySql/</c>.
/// </summary>
public sealed class MySqlRadioPadDbContext : RadioPadDbContext
{
    public MySqlRadioPadDbContext(DbContextOptions<MySqlRadioPadDbContext> options) : base(options) { }
}
